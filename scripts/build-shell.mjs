import { mkdir, copyFile, readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { renderServiceWorker, serviceWorkerTemplate, shellVersion } from "../src/offline/shell.mjs";
await mkdir("public/icons", { recursive: true });
await mkdir("public/offline", { recursive: true });
for (const locale of ["vi", "en"])
  await copyFile(`src/messages/${locale}.json`, `public/offline/${locale}.json`);
for (const subset of ["latin", "vietnamese"])
  await copyFile(
    `node_modules/@fontsource/be-vietnam-pro/files/be-vietnam-pro-${subset}-400-normal.woff2`,
    `public/offline/be-vietnam-pro-${subset}.woff2`,
  );
const svg =
  '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><rect width="512" height="512" rx="100" fill="#e5dbee"/><circle cx="256" cy="256" r="160" fill="#236553"/><path d="M174 333C110 212 237 143 355 153C369 282 268 383 174 333Z" fill="#e5dbee"/><path d="M155 366L301 219" stroke="#236553" stroke-width="18" stroke-linecap="round"/></svg>';
for (const size of [192, 512])
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(`public/icons/icon-${size}.png`);
// Hashed after the icons are rendered, so an icon-only change also installs a new shell.
const template = await readFile(serviceWorkerTemplate, "utf8");
const version = await shellVersion((path) => readFile(`public${path}`), template);
await writeFile(
  "public/sw.js",
  "/* Generated by scripts/build-shell.mjs. Do not edit manually. */\n" +
    renderServiceWorker(template, version),
);
console.log("Prepared public offline translations and PWA icons.");
