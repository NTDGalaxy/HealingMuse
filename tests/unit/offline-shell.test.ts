import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  renderServiceWorker,
  serviceWorkerTemplate,
  shellFiles,
  shellVersion,
} from "../../src/offline/shell.mjs";
import { locales } from "@/lib/routes";

const template = readFileSync(serviceWorkerTemplate, "utf8");
const publicFile = async (path: string) => readFileSync(`public${path}`);

describe("offline shell", () => {
  it("allowlists public shell assets only, never pages, APIs or audio", () => {
    expect(new Set(shellFiles).size).toBe(shellFiles.length);
    for (const path of shellFiles) {
      expect(path).toMatch(
        /^\/(offline|gardens|icons)\/[\w.-]+\.(html|js|css|json|woff2|avif|png)$/,
      );
      expect(existsSync(`public${path}`)).toBe(true);
    }
  });

  it("lists every asset the offline page loads", () => {
    const html = readFileSync("public/offline/index.html", "utf8");
    const css = readFileSync("public/offline/style.css", "utf8");
    // Scripts, stylesheets, fonts, posters and translations; links to app pages stay network-only.
    const referenced = [
      ...[...html.matchAll(/<(?:script|link)\b[^>]*\b(?:src|href)="(\/[^"]+)"/g)].map(
        (match) => match[1],
      ),
      ...[...css.matchAll(/url\("?(\/[^")]+)"?\)/g)].map((match) => match[1]),
      ...locales.map((locale) => `/offline/${locale}.json`),
    ];
    expect(referenced).toHaveLength(9);
    expect(shellFiles).toEqual(expect.arrayContaining(referenced));
  });

  it("renders the version and the shell list into the template exactly once", () => {
    const source = renderServiceWorker(template, "healingmuse-shell-test");
    expect(source).toContain('const VERSION = "healingmuse-shell-test";');
    expect(source).not.toMatch(/__SHELL_(VERSION|FILES)__/);
    for (const path of shellFiles) expect(source).toContain(`  ${JSON.stringify(path)},\n`);
    expect(() => renderServiceWorker(template.replace("__SHELL_FILES__", "[]"), "v")).toThrow(
      /__SHELL_FILES__/,
    );
    expect(() => renderServiceWorker(`${template}\n__SHELL_FILES__`, "v")).toThrow(/exactly once/);
  });

  it("changes the version when only an icon changes", async () => {
    const original = await shellVersion(publicFile, template);
    expect(original).toMatch(/^healingmuse-shell-[0-9a-f]{16}$/);
    expect(await shellVersion(publicFile, template)).toBe(original);
    const changedIcon = async (path: string) =>
      path === "/icons/icon-192.png"
        ? Buffer.concat([await publicFile(path), Buffer.from([0])])
        : publicFile(path);
    expect(await shellVersion(changedIcon, template)).not.toBe(original);
    expect(await shellVersion(publicFile, `${template}\n`)).not.toBe(original);
  });

  it("matches the committed public/sw.js", async () => {
    const version = await shellVersion(publicFile, template);
    expect(readFileSync("public/sw.js", "utf8")).toBe(
      "/* Generated by scripts/build-shell.mjs. Do not edit manually. */\n" +
        renderServiceWorker(template, version),
    );
  });
});
